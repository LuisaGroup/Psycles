int main(int argc, char **argv) {
  const auto backend = std::string_view{argc > 1 ? argv[1] : "hip"};
  std::vector<std::uint32_t> words;
  words.reserve(operation_count * vector_math_word_count);
  for (auto operation = std::size_t{}; operation < operation_count;
       ++operation) {
    append_payload(
        words,
        SVMNodeVectorMath{
            .math_type = static_cast<NodeVectorMathType>(operation),
            .a = input_float3(static_cast<SVMStackOffset>(a_offset)),
            .b = input_float3(static_cast<SVMStackOffset>(b_offset)),
            .c = input_float3(static_cast<SVMStackOffset>(c_offset)),
            .param1 = input_float(static_cast<SVMStackOffset>(param1_offset)),
            .value_offset = static_cast<SVMStackOffset>(value_offset),
            .vector_offset = static_cast<SVMStackOffset>(vector_offset),
            ._pad = {0u, 0u}});
  }

  Context context{argv[0]};
  auto device = context.create_device(backend);
  auto stream = device.create_stream();
  auto word_buffer = device.create_buffer<std::uint32_t>(words.size());
  auto output_buffer =
      device.create_buffer<luisa::float4>(operation_count * 4u);
  auto cursor_buffer =
      device.create_buffer<std::uint32_t>(operation_count * 2u);
  auto shader = device.compile(
      vector_math_kernel(),
      ShaderOption{.enable_cache = false, .enable_fast_math = false});
  std::array<luisa::float4, operation_count * 4u> actual{};
  std::array<std::uint32_t, operation_count * 2u> cursors{};
  stream << word_buffer.copy_from(luisa::span{words})
         << shader(word_buffer, output_buffer, cursor_buffer)
                .dispatch(operation_count)
         << output_buffer.copy_to(luisa::span{actual})
         << cursor_buffer.copy_to(luisa::span{cursors}) << synchronize();

  for (auto operation = std::size_t{}; operation < operation_count;
       ++operation) {
    const auto &expected = oracle[operation];
    const auto plain = actual[operation * 4u];
    const auto dual = actual[operation * 4u + 1u];
    const auto dual_dx = actual[operation * 4u + 2u];
    const auto dual_dy = actual[operation * 4u + 3u];
    if (!near(plain.xyz(), expected.plain_vector) ||
        !near(plain.w, expected.plain_value) ||
        !near(dual.xyz(), expected.dual_vector) ||
        !near(luisa::float3{dual.w, dual_dx.w, dual_dy.w},
              expected.dual_value) ||
        !near(dual_dx.xyz(), expected.dual_vector_dx) ||
        !near(dual_dy.xyz(), expected.dual_vector_dy) ||
        cursors[operation * 2u] != vector_math_word_count ||
        cursors[operation * 2u + 1u] != vector_math_word_count) {
      std::cerr << "Cycles Vector Math oracle mismatch on " << backend
                << ", operation=" << operation << '\n';
      return EXIT_FAILURE;
    }
  }
  return EXIT_SUCCESS;
}
