template <typename T>
void append_payload(std::vector<std::uint32_t> &words, const T &payload) {
  const auto encoded = std::bit_cast<
      std::array<std::uint32_t, sizeof(T) / sizeof(std::uint32_t)>>(payload);
  words.insert(words.end(), encoded.begin(), encoded.end());
}

[[nodiscard]] auto vector_math_kernel() {
  return Kernel1D<Buffer<std::uint32_t>, Buffer<luisa::float4>,
                  Buffer<std::uint32_t>>{
      [](BufferUInt words, BufferFloat4 output, BufferUInt cursors) noexcept {
        const UInt index = dispatch_x();
        svm_detail::Stack plain_stack;
        svm_detail::stack_store_float3(plain_stack, a_offset,
                                       make_float3(1.25f, -0.75f, 0.4f));
        svm_detail::stack_store_float3(plain_stack, b_offset,
                                       make_float3(0.5f, 1.5f, -0.8f));
        svm_detail::stack_store_float3(plain_stack, c_offset,
                                       make_float3(-0.3f, 0.7f, 1.2f));
        svm_detail::stack_store_float(plain_stack, param1_offset, 0.65f);
        UInt plain_cursor = index * vector_math_word_count;
        svm_detail::Cursor plain_words{words, plain_cursor};
        svm_detail::node_vector_math(plain_words, plain_stack, false);
        output.write(index * 4u,
                     make_float4(svm_detail::stack_load_float3(
                                     plain_stack, vector_offset),
                                 svm_detail::stack_load_float(
                                     plain_stack, value_offset)));

        svm_detail::Stack dual_stack;
        svm_detail::stack_store_dual3(
            dual_stack, a_offset,
            {.val = make_float3(1.25f, -0.75f, 0.4f),
             .dx = make_float3(0.1f, -0.2f, 0.05f),
             .dy = make_float3(-0.07f, 0.03f, 0.11f)});
        svm_detail::stack_store_dual3(
            dual_stack, b_offset,
            {.val = make_float3(0.5f, 1.5f, -0.8f),
             .dx = make_float3(-0.04f, 0.08f, 0.12f),
             .dy = make_float3(0.09f, -0.06f, 0.02f)});
        svm_detail::stack_store_dual3(
            dual_stack, c_offset,
            {.val = make_float3(-0.3f, 0.7f, 1.2f),
             .dx = make_float3(0.03f, 0.07f, -0.09f),
             .dy = make_float3(-0.02f, 0.04f, 0.06f)});
        svm_detail::stack_store_dual1(
            dual_stack, param1_offset,
            {.val = 0.65f, .dx = 0.025f, .dy = -0.035f});
        UInt dual_cursor = index * vector_math_word_count;
        svm_detail::Cursor dual_words{words, dual_cursor};
        svm_detail::node_vector_math(dual_words, dual_stack, true);
        output.write(index * 4u + 1u,
                     make_float4(svm_detail::stack_load_float3(
                                     dual_stack, vector_offset),
                                 svm_detail::stack_load_float(
                                     dual_stack, value_offset)));
        output.write(index * 4u + 2u,
                     make_float4(svm_detail::stack_load_float3(
                                     dual_stack, vector_offset + 3u),
                                 svm_detail::stack_load_float(
                                     dual_stack, value_offset + 1u)));
        output.write(index * 4u + 3u,
                     make_float4(svm_detail::stack_load_float3(
                                     dual_stack, vector_offset + 6u),
                                 svm_detail::stack_load_float(
                                     dual_stack, value_offset + 2u)));
        cursors.write(index * 2u,
                      plain_cursor - index * vector_math_word_count);
        cursors.write(index * 2u + 1u,
                      dual_cursor - index * vector_math_word_count);
      }};
}

[[nodiscard]] bool near(float actual, float expected,
                        float tolerance = 2.0e-4f) noexcept {
  return std::isfinite(actual) &&
         std::abs(actual - expected) <=
             tolerance * std::max(1.0f, std::abs(expected));
}

[[nodiscard]] bool near(luisa::float3 actual, luisa::float3 expected) noexcept {
  return near(actual.x, expected.x) && near(actual.y, expected.y) &&
         near(actual.z, expected.z);
}

